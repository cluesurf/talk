/**
 * Normalizes the rhyme similarity map so that:
 * 1. Every consonant maps to every other consonant
 * 2. Symmetry is enforced (a->b = b->a)
 * 3. Missing pairs default to 0
 */
function normalizeRhymeSimilarities(
  mappings: RhymeSimilarities,
): Record<string, Record<string, number>> {
  const normalized: Record<string, Record<string, number>> = {}

  // First pass: collect all defined similarities (including reverse lookups)
  for (const [source, targets] of Object.entries(mappings)) {
    for (const [target, score] of Object.entries(targets)) {
      // Set forward mapping
      normalized[source] ??= {}
      normalized[source][target] = score

      // Set reverse mapping (symmetry)
      normalized[target] ??= {}
      // Only set if not already defined (prefer explicit definitions)
      normalized[target][source] ??= score
    }
  }

  // Second pass: ensure every consonant maps to every other consonant
  for (const source of ALL_CONSONANTS) {
    for (const target of ALL_CONSONANTS) {
      // Self-similarity is always 1, otherwise default to 0
      normalized[source] ??= {}
      normalized[source][target] ??= source === target ? 1 : 0
    }
  }

  return normalized
}

