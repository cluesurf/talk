import uniq from 'lodash/uniq'

export const sortLength = (a: string, b: string) => {
  const diff = b.length - a.length
  if (!diff) {
    return a.localeCompare(b)
  }
  return diff
}

const noDuplicateSounds = (s: string) => {
  if (!s.trim()) {
    return false
  }

  let i = 0
  while (i < s.length) {
    const a = s[i++]!
    const b = s[i]
    if (!b) {
      return true
    }
    if (a === b) {
      return false
    }
  }
}

